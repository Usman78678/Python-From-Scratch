a = "Usman-Abdullah"
print (len(a)) # Length of the string
print (a.upper()) # Convert to uppercase
print (a.lower()) # Convert to lowercase
print (a.replace("Abdullah", "Khan")) # Replace substring
print (a.split("-")) # Split string into a list
print (a.endswith("llah")) # Check if string ends with a substring
print (a.startswith("usm")) # Check if string starts with a substring (case-sensitive)
print (a.find("Abd")) # Find the starting index of a substring