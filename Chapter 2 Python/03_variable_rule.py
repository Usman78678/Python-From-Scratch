# Valid variable names
age = 21
student_name = "Usman"
_marks = 85
score2 = 90
totalMarks = 175

print(age)
print(student_name)
print(_marks)
print(score2)
print(totalMarks)

# Variable names are case-sensitive
Age = 25
print(Age)      # Different from 'age'

# Invalid variable names (will cause errors if uncommented)
# 2marks = 50        # Cannot start with a number
# total-marks = 80  # Hyphen not allowed
# class = 10        # 'class' is a keyword
# student name = "Ali"  # Spaces not allowed
